const fs = require('fs');
const path = require('path');

const units = ['usa', 'weimar_nazi_germany', 'edexcel_medicine', 'cme_new', 'eee'];

console.log('========================================================================');
console.log('🔗 VERIFYING EVERY SINGLE IN-APP DOWNLOAD LINK GENERATED BY VIEWS.JS');
console.log('========================================================================\n');

let totalChecked = 0;
let deadLinks = [];

for (const unitId of units) {
  const json = require(`../public/data/${unitId}.json`);
  const mocks = json.mock_exams || [];
  console.log(`📌 Unit: ${unitId} (${mocks.length} mocks registered)`);

  const hasSeparateBooklets = unitId === 'weimar_nazi_germany' || unitId === 'usa' || unitId === 'edexcel_medicine';

  for (const mock of mocks) {
    const mockId = mock.id;
    let expectedPdfs = [];
    if (hasSeparateBooklets) {
      expectedPdfs.push({ url: `/pdfs/mocks/${unitId}/${mockId}_question_booklet.pdf`, desc: '16p Question Booklet' });
      expectedPdfs.push({ url: `/pdfs/mocks/${unitId}/${mockId}_sources_booklet.pdf`, desc: '4p Sources Booklet' });
      expectedPdfs.push({ url: `/pdfs/mocks/${unitId}/${mockId}.pdf`, desc: '20p Complete Pack' });
    } else {
      expectedPdfs.push({ url: `/pdfs/mocks/${unitId}/${mockId}.pdf`, desc: 'Paper PDF' });
    }

    const hasMs = Boolean(
      mock.has_mark_scheme ||
      mock.mark_scheme_url ||
      unitId === 'weimar_nazi_germany' ||
      unitId === 'eee' ||
      unitId === 'usa' ||
      (unitId === 'edexcel_medicine' && mock.id !== 'mock_2025_clone')
    );
    if (hasMs) {
      expectedPdfs.push({ url: `/pdfs/mocks/${unitId}/${mockId}_mark_scheme.pdf`, desc: 'Teacher Mark Scheme PDF' });
    }

    // Interactive HTML files
    const paperUrl = mock.url || `${mock.id}.html`;
    const fullPaperUrl = paperUrl.startsWith('/') ? paperUrl : `/units/${unitId}/${paperUrl}`;
    const htmlPath = path.join('public', fullPaperUrl.replace(/^\/+/, ''));
    totalChecked++;
    if (!fs.existsSync(htmlPath)) {
      deadLinks.push(`[DEAD LINK] Interactive HTML missing: ${htmlPath} (from mock ${mockId})`);
    }

    for (const pdfItem of expectedPdfs) {
      totalChecked++;
      const localPdf = path.join('public', pdfItem.url.replace(/^\/+/, ''));
      if (!fs.existsSync(localPdf)) {
        deadLinks.push(`[DEAD LINK] ${pdfItem.desc} missing: ${pdfItem.url} (expected at ${localPdf})`);
      }
    }
  }
}

console.log(`\n========================================================================`);
console.log(`📊 TOTAL DOWNLOAD & VIEW BUTTONS CHECKED: ${totalChecked}`);
if (deadLinks.length === 0) {
  console.log(`🎉 100% OF ALL IN-APP MOCK LINKS EXIST ON DISK AND ARE FULLY FUNCTIONAL!`);
} else {
  console.log(`❌ DEAD LINKS DETECTED (${deadLinks.length}):`);
  deadLinks.forEach(d => console.log('  -', d));
}
console.log(`========================================================================\n`);
